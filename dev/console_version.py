def pick_items(items):
    """显示一组活动，让用户输入选中的题号，返回选中个数。"""
    n = len(items)
    while True:
        raw = input("  选中的题号（空格分隔，如 1 3 5；直接回车 = 一个都不选）：").strip()
        if raw == "":
            return 0

        # 把中文逗号、英文逗号都当成空格
        raw = raw.replace("，", " ").replace(",", " ")
        try:
            nums = {int(x) for x in raw.split()}
        except ValueError:
            print("  只能输入数字哦，比如：1 3 5")
            continue

        if any(x < 1 or x > n for x in nums):
            print(f"  题号要在 1~{n} 之间，再输一次。")
        else:
            return len(nums)


def read_rating(label):
    """读一个 1~7 的自评分。"""
    while True:
        raw = input(f"  {label}（1~7，数字越大能力越强）：").strip()
        if raw in ("1", "2", "3", "4", "5", "6", "7"):
            return int(raw)
        print("  只能填 1、2、3、4、5、6、7。")


